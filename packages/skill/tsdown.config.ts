import { defineConfig } from "tsdown";

// 2026-10-12: the skill ships as ONE self-contained file, so installing it
// copies a folder and nothing is downloaded or spawned at runtime (skills.sh's
// scanners flagged the old first-run `npm install`). Everything but Node's
// built-ins is inlined, unminified so a reviewer can read it, and CI fails if
// the committed bundle differs from a fresh build of src/.
export default defineConfig({
  entry: { bskts: "src/bskts.mjs" },
  format: "esm",
  platform: "node",
  target: "node20",
  outDir: "../../skills/bskts/scripts",
  clean: false,
  dts: false,
  sourcemap: false,
  minify: false,
  noExternal: [/.*/],
  external: [/^node:/],
  outExtensions: () => ({ js: ".mjs" }),
  // viem lazy-loads a few modules; inline them so the skill stays one file
  outputOptions: { inlineDynamicImports: true },
  banner: {
    js: "// GENERATED by packages/skill (pnpm run build) from packages/skill/src/bskts.mjs. Do not edit.\n// Inlines @bskts/sdk, viem and zod at this repo's locked versions; nothing is installed at runtime.",
  },
});
